import pandas as pd
import numpy as np
import os
import copy
import matplotlib.pyplot as plt

import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score

# Set reproducible seeds
np.random.seed(42)
torch.manual_seed(42)

# 1. DATA PREPROCESSING PIPELINE
print("[1/5] Loading and preprocessing diabetic_data.cv...")
df = pd.read_csv("diabetic_data.csv")

# Clean missing values marked as '?'
df.replace('?', np.nan, inplace=True)

# Drop high-missingness identifiers and irrelevant columns
drop_cols = ['encounter_id', 'patient_nbr', 'weight', 'payer_code', 'medical_speciality']
df.drop(columns=[c for c in drop_cols if c in df.columns], inplace=True)

# Target formulation: Readmission within 30 days (1) vs Other (0)
df['target'] = df['readmitted'].apply(lambda x: 1 if x == '<30' else 0)
df.drop(columns=['readmitted'], inplace=True)

# Handle categorical and numerical columns
num_cols = df.select_dtypes(include=['int64', 'float64']).columns.drop('target')
cat_cols = df.select_dtypes(include=['object']).columns

# Fill missing values
for col in num_cols:
    df[col].fillna(df[col].median(), inplace=True)
for col in cat_cols:
    df[col].fillna(df[col].mode()[0], inplace=True)

# One-Hot Encoding for top categorical categories
df_encoded = pd.get_dummies (df, columns=cat_cols, drop_first=True)

X = df_encoded.drop(columns=['target']).values.astype(np.float32)
y = df_encoded['target'].values.astype (np.float32)

# Train/Test Split (80% Train, 20% Global Holdout Test)
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=42, stratify=y)

# Feature Scaling
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)

X_test = scaler.transform(X_test)

# NEURAL NETWORK ARCHITECTURE

class ClinicalMLP(nn.Module):
    def __init__(self, input_dim):
        super(ClinicalMLP, self).__init__()
        self.network = nn.Sequential(
            nn.Linear(input_dim, 64),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(64, 32),
            nn.BatchNorm1d(32),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(32, 1)
        )

    def forward(self, x):
        return self.network(x).squeeze(1)

criterion = nn.BCEWithLogitsLoss()

def evaluate_model(model, X_val, y_val):
    model.eval()
    with torch.no_grad():
        inputs = torch.tensor(X_val, dtype=torch.float32)
        logits = model(inputs)
        probs = torch.sigmoid(logits).numpy()
        preds = (probs >= 0.5).astype(int)

    acc = accuracy_score(y_val, preds)
    prec = precision_score(y_val, preds, zero_division=0)
    rec = recall_score(y_val, preds, zero_division=0)
    f1 = f1_score(y_val, preds, zero_division=0)
    auc = roc_auc_score(y_val, probs)
    return acc, prec, rec, f1, auc

# 3. BENCHMARK A: CENTRALIZED TRAINING BASELINE

print("\n[2/5] Training Centralized Baseline Model...")
input_dim = X_train.shape[1]
central_model = ClinicalMLP(input_dim)
optimizer = optim.Adam (central_model.parameters(), lr=0.001, weight_decay=1e-4)

train_dataset = TensorDataset(torch.tensor(X_train), torch.tensor(y_train))
train_loader = DataLoader(train_dataset, batch_size=256, shuffle=True)

central_model.train()
for epoch in range(10):
    for batch_x, batch_y in train_loader:
        optimizer.zero_grad()
        outputs = central_model(batch_x)
        loss = criterion(outputs, batch_y)
        loss.backward()
        optimizer.step()

cent_acc, cent_prec, cent_rec, cent_f1, cent_auc = evaluate_model(central_model, X_test, y_test)
print(f"Centralized Results -> Acc: {cent_acc:.4f}, AUC: {cent_auc:.4f}, F1: {cent_f1:.4f}")

# 4. PARTITIONING NON-IID DATA INTO 3 CLINICAL NODES

print("\n[3/5] Partitioning data across 3 simulated Hospital Nodes...")
num_clients = 3
# Non-IID Dirichlet distribution simulation
indices = np.arange(len(X_train))
np.random.shuffle(indices)
client_splits = np.array_split(indices, num_clients)

client_data = []
for split in client_splits:
    c_x, c_y = X_train[split], y_train[split]
    ds = TensorDataset(torch.tensor(c_x), torch.tensor(c_y))
    client_data.append(DataLoader(ds, batch_size=128, shuffle=True, drop_last=True))

# 5. BENCHMARK B & C: FEDAVG & FEDAVG + DIFFERENTIAL PRIVACY

def train_federated(use_dp=False, clip_norm=1.0, noise_multiplier=0.01, rounds=10, local_epochs=2):
    global_model = ClinicalMLP(input_dim)
    auc_history = []

    for r in range(rounds):
        local_weights = []

        for client_id, dataloader in enumerate(client_data):
            local_model = copy.deepcopy(global_model)
            local_optimizer = optim.Adam(local_model.parameters(), lr=0.001)
            local_model.train()

            for _ in range(local_epochs):
                for bx, by in dataloader:
                    local_optimizer.zero_grad()
                    out = local_model(bx)
                    loss = criterion(out, by)
                    loss.backward()

                    if use_dp:
                        # Gradient Clipping
                        nn.utils.clip_grad_norm_(local_model.parameters(), max_norm=clip_norm)
                        # Add Gaussian Noise to Gradients
                        for p in local_model.parameters():
                            if p.grad is not None:
                                noise = torch.randn_like(p.grad) * (noise_multiplier * clip_norm)
                                p.grad += noise

                    local_optimizer.step()

            local_weights.append(local_model.state_dict())

        # Federated Averaging (FedAvg)
        avg_weights = copy.deepcopy(local_weights[0])
        for key in avg_weights.keys():
            for i in range(1, len(local_weights)):
                avg_weights[key] += local_weights[i][key]
            avg_weights[key] = torch.div(avg_weights[key], len(local_weights))

        global_model.load_state_dict(avg_weights)
        _, _, _, _, current_auc = evaluate_model(global_model, X_test, y_test)
        auc_history.append(current_auc)

    acc, prec, rec, f1, auc = evaluate_model(global_model, X_test, y_test)
    return global_model, (acc, prec, rec, f1, auc), auc_history

print("\n[4/5] Running Standard FedAvg...")
fed_model, fed_metrics, fed_auc_hist = train_federated(use_dp=False, rounds=10)
print(f"FedAvg Results -> Acc: {fed_metrics[0]:.4f}, AUC: {fed_metrics[4]:.4f}, F1: {fed_metrics[3]:.4f}")

print("\n[5/5] Running FedAvg + Differential Privacy (DP-FedAvg)...")
dp_fed_model, dp_metrics, dp_auc_hist = train_federated(use_dp=True, clip_norm=1.0, noise_multiplier=0.005, rounds=10)
print(f"DP-FedAvg Results -> Acc: {dp_metrics[0]:.4f}, AUC: {dp_metrics[4]:.4f}, F1: {dp_metrics[3]:.4f}")

plt.figure(figsize=(8, 5), dpi=300)
plt.plot(range(1, 11), fed_auc_hist, marker='o', label='Standard FedAvg (Non-IID)', color='#1f77b4', linewidth=2)
plt.plot(range(1, 11), dp_auc_hist, marker='s', label='DP-FedAvg (ε-calibrated Noise)', color='#d62728', linewidth=2)
plt.axhline(y=cent_auc, color='green', linestyle='--', label=f'Centralized Benchmark ({cent_auc:.3f})')
plt.title("Convergence Comparison: Diabetic Readmission Prediction Across Clinical Nodes", fontsize=11, fontweight='bold')
plt.xlabel("Communication Rounds", fontsize=10)
plt.ylabel("ROC-AUC Score", fontsize=10)
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend(loc='lower right')
plt.tight_layout()
plt.savefig("federated_learning_convergence.png")
plt.show()

